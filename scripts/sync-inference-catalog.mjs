import { readFileSync, writeFileSync, renameSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format } from 'prettier';
import { refreshSources, validateSource } from './lib/inference-catalog/sources.mjs';
import { buildCatalog } from './lib/inference-catalog/normalize.mjs';
import {
  buildMarketplaceProvider,
  FEATURED_LIVE_MODEL_IDS,
} from './lib/inference-catalog/fixtures.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = new Set(process.argv.slice(2).filter((arg) => arg !== '--'));
for (const arg of args)
  if (!['--cached', '--check'].includes(arg)) throw new Error(`Unknown option ${arg}`);
const cached = args.has('--cached');
const check = args.has('--check');
const read = (path, fallback) => {
  try {
    return JSON.parse(readFileSync(resolve(root, path), 'utf8'));
  } catch (error) {
    if (error.code === 'ENOENT') return fallback;
    throw error;
  }
};
const snapshotPath = 'packages/constants/data/inference-sources.json';
const overrides = read('packages/constants/data/inference-overrides.json');
const previous = read(snapshotPath, { version: 1, sources: {} });
const sources = cached
  ? previous.sources
  : await refreshSources(previous.sources, overrides.providerAliases);
for (const [key, source] of Object.entries(sources)) validateSource(key, source.payload);
if (!sources.models || !sources.providers)
  throw new Error('No models.dev snapshot. Run pnpm bossraid sync:inference-catalog first.');
const { catalog, excluded } = buildCatalog(sources, overrides);
const old = read('packages/constants/data/inference-model-pricing.json', { models: [] });
const oldById = new Map(old.models.map((m) => [m.modelId, m]));
const newById = new Map(catalog.map((m) => [m.modelId, m]));
const ageDays = (date) => (Date.now() - Date.parse(date)) / 86_400_000;
const stale = Object.entries(sources)
  .filter(([, s]) => ageDays(s.checkedAt ?? s.fetchedAt) > 7 || s.error)
  .map(([key]) => key);
const report = {
  sourceStatus: Object.fromEntries(
    Object.entries(sources).map(([key, s]) => [
      key,
      {
        url: s.url,
        fetchedAt: s.fetchedAt,
        checkedAt: s.checkedAt,
        sha256: s.sha256,
        error: s.error,
      },
    ])
  ),
  providerCounts: Object.fromEntries(
    [...new Set(catalog.map((m) => m.modelProvider))].map((p) => [
      p,
      catalog.filter((m) => m.modelProvider === p).length,
    ])
  ),
  excluded,
};
const comparable = ({ source, ...model }) =>
  JSON.stringify({ ...model, source: source ? { ...source, fetchedAt: undefined } : undefined });
const drift = {
  added: catalog.filter((m) => !oldById.has(m.modelId)).map((m) => m.modelId),
  removed: old.models.filter((m) => !newById.has(m.modelId)).map((m) => m.modelId),
  changed: catalog
    .filter((m) => oldById.has(m.modelId) && comparable(m) !== comparable(oldById.get(m.modelId)))
    .map((m) => m.modelId),
  stale: cached ? [] : stale,
};
console.log(JSON.stringify({ models: catalog.length, ...report.providerCounts, drift }, null, 2));
if (check) {
  if (Object.values(drift).some((rows) => rows.length)) process.exitCode = 1;
} else {
  const generatedAt = Object.values(sources)
    .map((s) => s.fetchedAt)
    .sort()
    .at(-1);
  const providers = Object.fromEntries(
    Object.keys(report.providerCounts).map((p) => [
      p,
      {
        modelCount: report.providerCounts[p],
        models: catalog.filter((m) => m.modelProvider === p),
      },
    ])
  );
  let port = 9100;
  const outputs = {
    [snapshotPath]: JSON.stringify({ version: 1, sources }),
    'packages/constants/src/inference-catalog-status.ts': `/* generated by scripts/sync-inference-catalog.mjs */\nexport const INFERENCE_CATALOG_SOURCE_STATUS = ${JSON.stringify(report.sourceStatus)};\n`,
    'packages/constants/src/inference-catalog.ts': `/* generated by scripts/sync-inference-catalog.mjs */\nimport type { InferenceCatalogEntry } from './inference-catalog-types.js';\nimport type { UpstreamProviderId } from './upstream-providers.js';\nexport type { InferenceCatalogEntry } from './inference-catalog-types.js';\nexport const INFERENCE_MODEL_CATALOG: InferenceCatalogEntry[] = ${JSON.stringify(catalog)};\nconst inferenceCatalogEntryByModelId = new Map(INFERENCE_MODEL_CATALOG.map((entry) => [entry.modelId, entry]));\nconst inferenceCatalogEntriesByProvider = new Map<UpstreamProviderId, InferenceCatalogEntry[]>();\nconst inferenceCatalogEntryByUpstreamId = new Map<UpstreamProviderId, Map<string, InferenceCatalogEntry>>();\nfor (const entry of INFERENCE_MODEL_CATALOG) {\n  const providerEntries = inferenceCatalogEntriesByProvider.get(entry.modelProvider) ?? [];\n  providerEntries.push(entry);\n  inferenceCatalogEntriesByProvider.set(entry.modelProvider, providerEntries);\n  const providerUpstreamIds = inferenceCatalogEntryByUpstreamId.get(entry.modelProvider) ?? new Map();\n  for (const upstreamId of [entry.upstreamModelId, ...(entry.upstreamAliases ?? [])]) {\n    if (!providerUpstreamIds.has(upstreamId)) providerUpstreamIds.set(upstreamId, entry);\n  }\n  inferenceCatalogEntryByUpstreamId.set(entry.modelProvider, providerUpstreamIds);\n}\nconst inferenceCatalogModelIds = INFERENCE_MODEL_CATALOG.map((entry) => entry.modelId);\nexport function getInferenceCatalogEntry(modelId: string): InferenceCatalogEntry | undefined {\n  return inferenceCatalogEntryByModelId.get(modelId);\n}\nexport function getInferenceCatalogEntryByUpstreamId(provider: UpstreamProviderId, upstreamId: string): InferenceCatalogEntry | undefined {\n  return inferenceCatalogEntryByUpstreamId.get(provider)?.get(upstreamId);\n}\nexport function listInferenceCatalogEntriesForProvider(provider: UpstreamProviderId): readonly InferenceCatalogEntry[] {\n  return inferenceCatalogEntriesByProvider.get(provider) ?? [];\n}\nexport function listInferenceCatalogModelIds(): string[] { return [...inferenceCatalogModelIds]; }\n`,
    'packages/constants/src/inference-catalog-benchmark.ts': `/* generated by scripts/sync-inference-catalog.mjs */\nimport { INFERENCE_MODEL_CATALOG } from './inference-catalog.js';\nexport const CATALOG_BENCHMARK_INPUT_PER_1M_USD: Record<string, number> = Object.fromEntries(INFERENCE_MODEL_CATALOG.map(m=>[m.modelId,m.inputPer1mUsd]));\nexport const CATALOG_BENCHMARK_OUTPUT_PER_1M_USD: Record<string, number> = Object.fromEntries(INFERENCE_MODEL_CATALOG.map(m=>[m.modelId,m.outputPer1mUsd]));\nexport const CATALOG_BENCHMARK_TASK_USD: Record<string, number> = Object.fromEntries(INFERENCE_MODEL_CATALOG.map(m=>[m.modelId,Math.max(0.01,Number((m.inputPer1mUsd*0.001+m.outputPer1mUsd*0.001024).toFixed(4)))]));\n`,
    'packages/constants/data/inference-model-pricing.json': JSON.stringify({
      generatedAt,
      source: report.sourceStatus,
      providers,
      models: catalog,
    }),
    'packages/constants/data/inference-catalog-report.json': JSON.stringify(report),
    'examples/inference/inference-marketplace-providers.json': JSON.stringify(
      catalog.map((model) =>
        buildMarketplaceProvider(
          model,
          FEATURED_LIVE_MODEL_IDS.has(model.modelId) ? port++ : 9200,
          FEATURED_LIVE_MODEL_IDS.has(model.modelId)
        )
      )
    ),
  };
  // Prepare every output before replacing any existing artifact.
  for (const [path, body] of Object.entries(outputs))
    outputs[path] = await format(body, {
      filepath: path,
      singleQuote: true,
      trailingComma: 'es5',
      printWidth: 100,
    });
  for (const [path, body] of Object.entries(outputs)) {
    const target = resolve(root, path);
    writeFileSync(`${target}.tmp`, body);
    renameSync(`${target}.tmp`, target);
  }
  console.log(
    `[catalog] wrote ${catalog.length} models; ${excluded.length} excluded. ${stale.length ? `Stale sources: ${stale.join(', ')}` : 'All sources current.'}`
  );
}
