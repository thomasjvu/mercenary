  'phala/gemma-4-26b-a4b-uncensored',
  'venice-uncensored-1-2',
  'google-gemma-4-31b-it',
  'mistral-small-3-2-24b-instruct',
  'qwen3-5-9b',
  'deepseek-v3.2',
  'minimax-m27',
  'olafangensan-glm-4.7-flash-heretic',
