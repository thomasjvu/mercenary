import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const webRoot = path.join(repoRoot, 'apps/web');

async function loadIconSet(packageName) {
  const iconsPath = path.join(webRoot, 'node_modules', packageName, 'icons.json');
  return JSON.parse(await fs.readFile(iconsPath, 'utf8'));
}

const pixelData = await loadIconSet('@iconify-json/pixel');
const simpleIconsData = await loadIconSet('@iconify-json/simple-icons');
const webSrcDir = path.join(repoRoot, 'apps/web/src');
const outputPath = path.join(repoRoot, 'apps/web/src/lib/icon-subset-data.ts');

const iconSets = {
  pixel: pixelData,
  'simple-icons': simpleIconsData,
};

async function listSourceFiles(dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  const files = await Promise.all(
    entries.map(async (entry) => {
      const entryPath = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        return listSourceFiles(entryPath);
      }
      return /\.(ts|tsx)$/.test(entry.name) ? [entryPath] : [];
    })
  );
  return files.flat();
}

function collectIconNames(source) {
  const namesByPrefix = new Map();
  const matches = source.matchAll(/(?:pixel|simple-icons):[a-z0-9-]+/g);
  for (const match of matches) {
    const fullName = match[0];
    const [prefix, name] = fullName.split(':');
    if (!(prefix in iconSets)) {
      continue;
    }
    if (!namesByPrefix.has(prefix)) {
      namesByPrefix.set(prefix, new Set());
    }
    namesByPrefix.get(prefix).add(name);
  }
  return namesByPrefix;
}

function buildSubset(prefix, names) {
  const iconSet = iconSets[prefix];
  const icons = {};
  for (const name of [...names].sort()) {
    const icon = iconSet.icons[name];
    if (!icon) {
      throw new Error(`Missing icon "${prefix}:${name}" in @iconify-json/${prefix === 'simple-icons' ? 'simple-icons' : prefix}`);
    }
    icons[name] = { body: icon.body };
  }
  return {
    prefix,
    width: iconSet.width,
    height: iconSet.height,
    icons,
  };
}

async function main() {
  const files = await listSourceFiles(webSrcDir);
  const namesByPrefix = new Map();
  for (const file of files) {
    const source = await fs.readFile(file, 'utf8');
    for (const [prefix, names] of collectIconNames(source)) {
      if (!namesByPrefix.has(prefix)) {
        namesByPrefix.set(prefix, new Set());
      }
      for (const name of names) {
        namesByPrefix.get(prefix).add(name);
      }
    }
  }

  const pixelSubset = buildSubset('pixel', namesByPrefix.get('pixel') ?? new Set());
  const simpleSubset = buildSubset('simple-icons', namesByPrefix.get('simple-icons') ?? new Set());

  const contents = `// Generated by scripts/generate-web-icon-subset.mjs — do not edit by hand.
export const pixelIconSubset = ${JSON.stringify(pixelSubset, null, 2)} as const;

export const simpleIconSubset = ${JSON.stringify(simpleSubset, null, 2)} as const;
`;

  await fs.writeFile(outputPath, contents);
  console.log(
    `Wrote ${outputPath} (${Object.keys(pixelSubset.icons).length} pixel, ${Object.keys(simpleSubset.icons).length} simple-icons)`
  );
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});